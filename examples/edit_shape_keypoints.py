"""Minimal interactive keypoint editor for every packaged shape family.

Renders one shape and its named points, lets you drag them with the mouse, and writes them back into
the shape's own SVG. Deliberately trivial — no error handling, no undo.

Usage::

    uv run python examples/edit_shape_keypoints.py duck
    uv run python examples/edit_shape_keypoints.py anchor
    uv run python examples/edit_shape_keypoints.py r

Called without a shape (or with an unknown one), it prints what is available and exits.

Two document shapes are handled, matching what each family actually stores:

**Outline families** (animals, symbols) draw a filled silhouette from their ``<path id="outline">``
with landmark dots on top. Dragging moves a landmark over a fixed silhouette; saving rewrites the
``keypoints`` group and regenerates the ``skeleton`` group from the new positions.

**The letter family** stores a stroke graph and no outline at all, so there is nothing to fill:
the strokes themselves are drawn as thick lines and the nodes are the dots. Dragging a node moves
the letter's actual geometry, since the silhouette is generated by stroking that graph at load time.
Saving rewrites the ``nodes`` group and re-syncs every ``strokes``/``cuts`` line's endpoints to it.

Controls: press and hold the left mouse button on a dot to drag it, release to drop · ``s`` saves
back into the SVG · ``q`` (or closing the window) quits. Saving always overwrites the shape's own
SVG in place — no dialog, no prompt. The color/name legend sits under the canvas.

"""

