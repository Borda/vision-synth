def _cycled_palette(names: Sequence[str]) -> dict[str, str]:
    """Return one color per name, cycling :data:`_PALETTE_CYCLE` in schema order."""
    return {name: _PALETTE_CYCLE[i % len(_PALETTE_CYCLE)] for i, name in enumerate(names)}


@dataclass(frozen=True)
class Family:
    """One editable shape family: where its documents live and how they are drawn.

    Args:
        name: The family's short name, used in the window title and the shape listing.
        directory: The packaged asset directory holding ``<shape>.svg``.
        point_names: Every point name the family's schema defines, in schema order.
        palette: Fill color per point name.
        group_id: The ``<g>`` the draggable circles live in — ``"keypoints"`` for an outline family,
            ``"nodes"`` for the letter graph.
        skeleton: Edges to draw between points, as index pairs into ``point_names``. Empty for the
            letter family, whose edges come from the document itself rather than from one shared
            topology.
        is_graph: Whether documents carry a stroke graph instead of an outline. This is the whole
            difference between the two rendering paths, so it is one flag rather than two classes.

    """

    name: str
    directory: Path
    point_names: tuple[str, ...]
    palette: dict[str, str]
    group_id: str
    skeleton: tuple[tuple[int, int], ...]
    is_graph: bool = False

    def shapes(self) -> list[str]:
        """Return every shape this family has a packaged document for."""
        return sorted(path.stem for path in self.directory.glob("*.svg"))


